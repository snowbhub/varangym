function convertText(value) {
  let s=String(value||'')
  for(const [ru,uk] of PHRASES.sort((a,b)=>b[0].length-a[0].length)) s=s.replaceAll(ru,uk)
  for(const [ru,uk] of WORDS) s=s.replaceAll(ru,uk)
  // Clean several very visible Russian function words that survive inflected phrases.
  s=s.replace(/\bи\b/g,'і').replace(/\bили\b/g,'або').replace(/\bпри\b/g,'під час').replace(/\bдля\b/g,'для')
    .replace(/\bчтобы\b/g,'щоб').replace(/\bкогда\b/g,'коли').replace(/\bпока\b/g,'поки').replace(/\bесли\b/g,'якщо')
    .replace(/\bне\b/g,'не').replace(/\bс\b/g,'з').replace(/\bсо\b/g,'зі').replace(/\bк\b/g,'до').replace(/\bот\b/g,'від')
  return s
}

export function ukrainianizeInstructions(pack) {
  if (!pack || typeof pack !== 'object') return pack
  return Object.fromEntries(Object.entries(pack).map(([id,steps]) => [id,
    Array.isArray(steps) ? steps.map(convertText) : convertText(steps)
  ]))
}
