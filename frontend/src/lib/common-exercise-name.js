function normalize(name='') {
  return String(name).replace(/[–—]/g,'-').replace(/\s+/g,' ').trim()
}

export function commonExerciseName(name, lang) {
  const value=normalize(name)
  if(!value || (lang!=='uk'&&lang!=='ru')) return null
  for(const [pattern,uk,ru] of RULES) if(pattern.test(value)) return lang==='uk'?uk:ru
  return null
}
