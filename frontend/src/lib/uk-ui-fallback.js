function convert(value) {
  if (typeof value !== 'string') return value
  let s=value
  for(const [ru,uk] of PHRASES.sort((a,b)=>b[0].length-a[0].length)) s=s.replaceAll(ru,uk)
  return s
    .replace(/\bкотор(ый|ая|ое|ые|ого|ой|ому|ым|ых)\b/gi,'який')
    .replace(/\bчтобы\b/gi,'щоб').replace(/\bесли\b/gi,'якщо').replace(/\bкогда\b/gi,'коли')
    .replace(/\bздесь\b/gi,'тут').replace(/\bтеперь\b/gi,'тепер').replace(/\bтолько\b/gi,'лише')
    .replace(/\bможно\b/gi,'можна').replace(/\bнужно\b/gi,'потрібно').replace(/\bсейчас\b/gi,'зараз')
    .replace(/\bпосле\b/gi,'після').replace(/\bперед\b/gi,'перед').replace(/\bмежду\b/gi,'між')
    .replace(/\bкажд(ый|ая|ое|ые|ого|ой|ую|ом)\b/gi,'кожен').replace(/\bвсе\b/gi,'усі')
}

export function ukrainianizeUiPack(pack) {
  if (!pack || typeof pack !== 'object') return {}
  const out={}
  for(const [key,value] of Object.entries(pack)) {
    if(Array.isArray(value)) out[key]=value.map(convert)
    else if(value&&typeof value==='object') out[key]=Object.fromEntries(Object.entries(value).map(([k,v])=>[k,convert(v)]))
    else out[key]=convert(value)
  }
  return out
}
