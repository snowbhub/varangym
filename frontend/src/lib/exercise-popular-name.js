const clean = name => String(name||'').trim().toLowerCase().replace(/[–—]/g,'-').replace(/\s+/g,' ')

export function popularExerciseName(name, lang) {
  const key=clean(name)
  if(lang==='uk')return UA[key]||null
  if(lang==='ru')return RU[key]||null
  return null
}
